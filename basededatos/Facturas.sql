-- =========================================================
-- VendingMiniMarket
-- HU-33/HU-34: Facturas de proveedor
-- PostgreSQL / Supabase
-- =========================================================
-- Una factura de proveedor vincula una compra con productos,
-- costos e impuestos reales. Puede (opcionalmente) relacionarse
-- con un pedido (public.pedido, HU-30).
--
-- Estado: PENDIENTE (recien registrada, se resalta en amarillo),
-- EN_REVISION (el Encargado la reviso y la envia al Administrador),
-- APROBADA / RECHAZADA (decision final del Administrador, HU-34).
--
-- numero_factura es unico por proveedor (criterio de "factura
-- duplicada" de HU-33).
-- =========================================================

BEGIN;


-- =========================================================
-- 1. FACTURA_PROVEEDOR
-- =========================================================

CREATE TABLE IF NOT EXISTS public.factura_proveedor (

    id_factura BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_proveedor BIGINT NOT NULL,
    id_pedido BIGINT,
    id_ubicacion BIGINT NOT NULL,

    numero_factura VARCHAR(50) NOT NULL,

    fecha_emision TIMESTAMPTZ NOT NULL,
    fecha_vencimiento TIMESTAMPTZ,

    id_impuesto BIGINT NOT NULL,

    subtotal NUMERIC(12,2) NOT NULL
        CONSTRAINT chk_factura_subtotal
            CHECK (subtotal >= 0),

    monto_impuesto NUMERIC(12,2) NOT NULL
        CONSTRAINT chk_factura_monto_impuesto
            CHECK (monto_impuesto >= 0),

    monto_total NUMERIC(12,2) NOT NULL
        CONSTRAINT chk_factura_monto_total
            CHECK (monto_total >= 0),

    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CONSTRAINT chk_factura_estado
            CHECK (estado IN (
                'PENDIENTE', 'EN_REVISION', 'APROBADA', 'RECHAZADA'
            )),

    evidencia_url TEXT,
    observaciones VARCHAR(500),

    id_usuario_registra BIGINT NOT NULL,

    id_usuario_revisa BIGINT,
    fecha_revision TIMESTAMPTZ,

    id_usuario_valida BIGINT,
    fecha_validacion TIMESTAMPTZ,

    fecha_registro TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_factura_proveedor
        FOREIGN KEY (id_proveedor)
        REFERENCES public.proveedor(id_proveedor),

    CONSTRAINT fk_factura_pedido
        FOREIGN KEY (id_pedido)
        REFERENCES public.pedido(id_pedido),

    CONSTRAINT fk_factura_ubicacion
        FOREIGN KEY (id_ubicacion)
        REFERENCES public.ubicacion_inventario(id_ubicacion),

    CONSTRAINT fk_factura_impuesto
        FOREIGN KEY (id_impuesto)
        REFERENCES public.impuesto(id_impuesto),

    CONSTRAINT fk_factura_usuario_registra
        FOREIGN KEY (id_usuario_registra)
        REFERENCES public.usuario(id_usuario),

    CONSTRAINT fk_factura_usuario_revisa
        FOREIGN KEY (id_usuario_revisa)
        REFERENCES public.usuario(id_usuario),

    CONSTRAINT fk_factura_usuario_valida
        FOREIGN KEY (id_usuario_valida)
        REFERENCES public.usuario(id_usuario),

    CONSTRAINT uq_factura_proveedor_numero
        UNIQUE (id_proveedor, numero_factura)
);

CREATE INDEX IF NOT EXISTS idx_factura_proveedor
ON public.factura_proveedor(id_proveedor);

CREATE INDEX IF NOT EXISTS idx_factura_pedido
ON public.factura_proveedor(id_pedido);

CREATE INDEX IF NOT EXISTS idx_factura_estado
ON public.factura_proveedor(estado);


-- =========================================================
-- 2. FACTURA_PROVEEDOR_DETALLE
-- =========================================================

CREATE TABLE IF NOT EXISTS public.factura_proveedor_detalle (

    id_detalle BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_factura BIGINT NOT NULL,
    id_producto BIGINT NOT NULL,

    cantidad INT NOT NULL
        CONSTRAINT chk_factura_detalle_cantidad
            CHECK (cantidad > 0),

    costo_unitario NUMERIC(12,2) NOT NULL
        CONSTRAINT chk_factura_detalle_costo
            CHECK (costo_unitario >= 0),

    CONSTRAINT fk_factura_detalle_factura
        FOREIGN KEY (id_factura)
        REFERENCES public.factura_proveedor(id_factura),

    CONSTRAINT fk_factura_detalle_producto
        FOREIGN KEY (id_producto)
        REFERENCES public.producto(id_producto),

    CONSTRAINT uq_factura_detalle_producto
        UNIQUE (id_factura, id_producto)
);

CREATE INDEX IF NOT EXISTS idx_factura_detalle_factura
ON public.factura_proveedor_detalle(id_factura);


COMMIT;
