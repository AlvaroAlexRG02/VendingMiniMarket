ALTER TABLE public.usuario
    ADD COLUMN IF NOT EXISTS debe_cambiar_contrasena BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE public.usuario
    ADD COLUMN IF NOT EXISTS origen_cambio_contrasena VARCHAR(20) NOT NULL DEFAULT 'INICIAL';

CREATE TABLE IF NOT EXISTS public.recuperacion_contrasena (
    id_recuperacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL
        REFERENCES public.usuario (id_usuario),
    token_hash TEXT NOT NULL UNIQUE,
    fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    fecha_uso TIMESTAMPTZ,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_recuperacion_contrasena_usuario_estado
    ON public.recuperacion_contrasena (id_usuario, estado);
