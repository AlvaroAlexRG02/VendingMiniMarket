-- HU-43: ventas manuales y detalle de productos.
-- Requiere que las tablas base tienda, usuario, ubicacion_inventario y producto existan.

CREATE TABLE IF NOT EXISTS public.venta_manual (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tienda BIGINT NOT NULL REFERENCES public.tienda(id_tienda),
    id_ubicacion BIGINT NOT NULL REFERENCES public.ubicacion_inventario(id_ubicacion),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    metodo_pago VARCHAR(10) NOT NULL,
    referencia_sinpe VARCHAR(60),
    subtotal NUMERIC(12,2) NOT NULL,
    impuesto NUMERIC(12,2) NOT NULL,
    total NUMERIC(12,2) NOT NULL,
    observaciones VARCHAR(300),
    CONSTRAINT chk_venta_manual_metodo_pago CHECK (metodo_pago IN ('Efectivo', 'SINPE')),
    CONSTRAINT chk_venta_manual_sinpe CHECK (
        (metodo_pago = 'SINPE' AND NULLIF(BTRIM(referencia_sinpe), '') IS NOT NULL)
        OR (metodo_pago = 'Efectivo' AND referencia_sinpe IS NULL)
    ),
    CONSTRAINT chk_venta_manual_totales CHECK (
        subtotal >= 0 AND impuesto >= 0 AND total >= 0
    )
);

CREATE TABLE IF NOT EXISTS public.venta_manual_detalle (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT NOT NULL REFERENCES public.venta_manual(id_venta) ON DELETE CASCADE,
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
    porcentaje_impuesto NUMERIC(7,4) NOT NULL CHECK (porcentaje_impuesto >= 0),
    subtotal NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    impuesto NUMERIC(12,2) NOT NULL CHECK (impuesto >= 0),
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    CONSTRAINT uq_venta_manual_detalle_producto UNIQUE (id_venta, id_producto)
);

CREATE INDEX IF NOT EXISTS idx_venta_manual_tienda_fecha
    ON public.venta_manual (id_tienda, fecha DESC);

CREATE INDEX IF NOT EXISTS idx_venta_manual_usuario_fecha
    ON public.venta_manual (id_usuario, fecha DESC);
