-- HU-45 y HU-46: alertas de inventario activas e historial de gestion.
-- Ejecutar despues del inventario base, Seguridad.sql, Ventas.sql y Conciliacion.sql.

CREATE TABLE IF NOT EXISTS public.alerta_inventario (
    id_alerta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ubicacion BIGINT NOT NULL
        REFERENCES public.ubicacion_inventario(id_ubicacion),
    id_producto BIGINT NOT NULL
        REFERENCES public.producto(id_producto),
    tipo_alerta VARCHAR(20) NOT NULL
        CHECK (tipo_alerta IN ('bajo', 'cero', 'negativo')),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'ATENDIDA', 'CERRADA', 'DESCARTADA', 'RESUELTA')),
    stock_generacion INTEGER NOT NULL,
    stock_minimo_generacion INTEGER NOT NULL,
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_cierre TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_alerta_inventario_no_resuelta
    ON public.alerta_inventario (id_ubicacion, id_producto)
    WHERE estado <> 'RESUELTA';

CREATE INDEX IF NOT EXISTS idx_alerta_inventario_estado_fecha
    ON public.alerta_inventario (estado, fecha_generacion DESC);

CREATE INDEX IF NOT EXISTS idx_alerta_inventario_ubicacion_estado
    ON public.alerta_inventario (id_ubicacion, estado, tipo_alerta);

CREATE TABLE IF NOT EXISTS public.alerta_inventario_gestion (
    id_gestion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_alerta BIGINT NOT NULL
        REFERENCES public.alerta_inventario(id_alerta),
    id_usuario BIGINT
        REFERENCES public.usuario(id_usuario),
    accion VARCHAR(20) NOT NULL
        CHECK (accion IN ('GENERADA', 'ACTUALIZADA', 'ATENDIDA', 'CERRADA', 'DESCARTADA', 'RESUELTA')),
    evidencia VARCHAR(1000),
    observaciones VARCHAR(1000),
    justificacion VARCHAR(1000),
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_alerta_inventario_gestion_historial
    ON public.alerta_inventario_gestion (id_alerta, fecha DESC, id_gestion DESC);
