-- =========================================================
-- 1. CATEGORIA
-- =========================================================

CREATE TABLE IF NOT EXISTS public.categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(250),
    estado BOOLEAN NOT NULL DEFAULT TRUE
);


-- =========================================================
-- 2. PROVEEDOR
-- =========================================================

CREATE TABLE IF NOT EXISTS public.proveedor (
    id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL UNIQUE,
    contacto VARCHAR(150),
    telefono VARCHAR(30),
    correo VARCHAR(150),
    direccion VARCHAR(250),
    estado BOOLEAN NOT NULL DEFAULT TRUE
);


-- =========================================================
-- 3. IMPUESTO
-- =========================================================

CREATE TABLE IF NOT EXISTS public.impuesto (
    id_impuesto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    porcentaje NUMERIC(5,2) NOT NULL,
    descripcion VARCHAR(250),
    estado BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_impuesto_porcentaje
        CHECK (porcentaje >= 0 AND porcentaje <= 100)
);


-- =========================================================
-- 4. MARGEN_GANANCIA
-- =========================================================

CREATE TABLE IF NOT EXISTS public.margen_ganancia (
    id_margen BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    porcentaje NUMERIC(5,2) NOT NULL,
    descripcion VARCHAR(250),
    estado BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT chk_margen_porcentaje
        CHECK (porcentaje >= 0 AND porcentaje <= 100)
);


-- =========================================================
-- 5. PRODUCTO
-- =========================================================

CREATE TABLE IF NOT EXISTS public.producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_categoria BIGINT NOT NULL,
    id_proveedor BIGINT NOT NULL,
    id_impuesto BIGINT NOT NULL,

    codigo_articulo_retail VARCHAR(100) UNIQUE,
    codigo_barras VARCHAR(100) UNIQUE,

    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(300),

    estado BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_producto_categoria
        FOREIGN KEY (id_categoria)
        REFERENCES public.categoria(id_categoria),

    CONSTRAINT fk_producto_proveedor
        FOREIGN KEY (id_proveedor)
        REFERENCES public.proveedor(id_proveedor),

    CONSTRAINT fk_producto_impuesto
        FOREIGN KEY (id_impuesto)
        REFERENCES public.impuesto(id_impuesto)
);


-- =========================================================
-- 6. PRECIO_TIENDA
-- =========================================================

CREATE TABLE IF NOT EXISTS public.precio_tienda (
    id_precio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_producto BIGINT NOT NULL,
    id_tienda BIGINT NOT NULL,
    id_margen BIGINT NOT NULL,

    costo NUMERIC(12,2) NOT NULL,
    precio_sin_impuesto NUMERIC(12,2) NOT NULL,
    precio_venta NUMERIC(12,2) NOT NULL,

    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_fin TIMESTAMPTZ,

    estado BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_precio_producto
        FOREIGN KEY (id_producto)
        REFERENCES public.producto(id_producto),

    CONSTRAINT fk_precio_tienda
        FOREIGN KEY (id_tienda)
        REFERENCES public.tienda(id_tienda),

    CONSTRAINT fk_precio_margen
        FOREIGN KEY (id_margen)
        REFERENCES public.margen_ganancia(id_margen),

    CONSTRAINT chk_precio_costo
        CHECK (costo >= 0),

    CONSTRAINT chk_precio_sin_impuesto
        CHECK (precio_sin_impuesto >= 0),

    CONSTRAINT chk_precio_venta
        CHECK (precio_venta >= 0)
);
