BEGIN;


-- =========================================================
-- 1. TABLA MAQUINA
-- =========================================================
-- Cada máquina pertenece a una tienda.
-- El código de la máquina debe ser único.
-- Ejemplo:
-- VMM UL 001
-- VMM UP1 001
-- VMM UP2 003
-- =========================================================

CREATE TABLE IF NOT EXISTS public.maquina (

    id_maquina BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_tienda BIGINT NOT NULL,

    codigo VARCHAR(100) NOT NULL UNIQUE,

    nombre VARCHAR(150) NOT NULL,

    ubicacion VARCHAR(200),

    modelo VARCHAR(100),

    tipo VARCHAR(100),

    estado BOOLEAN NOT NULL DEFAULT TRUE,

    observaciones VARCHAR(500),

    fecha_registro TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_maquina_tienda
        FOREIGN KEY (id_tienda)
        REFERENCES public.tienda(id_tienda)
);


-- Índice para buscar rápidamente las máquinas de una tienda.

CREATE INDEX IF NOT EXISTS idx_maquina_tienda
ON public.maquina(id_tienda);


-- =========================================================
-- 2. TABLA MAQUINA_PRODUCTO
-- =========================================================
-- Define qué producto está configurado en cada canal
-- de una máquina.
--
-- Ejemplo:
--
-- Máquina VMM UL 001
--
-- Canal 1 -> Coca Cola
-- Canal 2 -> Monster
-- Canal 3 -> Fanta
--
-- capacidad = cantidad máxima que soporta ese canal.
--
-- El stock actual NO se guarda aquí.
-- Eso se manejará luego en el módulo de inventario.
-- =========================================================

CREATE TABLE IF NOT EXISTS public.maquina_producto (

    id_maquina_producto BIGINT
        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_maquina BIGINT NOT NULL,

    id_producto BIGINT NOT NULL,

    canal VARCHAR(50) NOT NULL,

    capacidad INT,

    estado BOOLEAN NOT NULL DEFAULT TRUE,

    fecha_actualizacion TIMESTAMPTZ
        NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_maquina_producto_maquina
        FOREIGN KEY (id_maquina)
        REFERENCES public.maquina(id_maquina),

    CONSTRAINT fk_maquina_producto_producto
        FOREIGN KEY (id_producto)
        REFERENCES public.producto(id_producto),

    CONSTRAINT chk_maquina_producto_capacidad
        CHECK (
            capacidad IS NULL
            OR capacidad >= 0
        ),

    -- Una máquina no puede tener dos configuraciones
    -- diferentes para el mismo canal.

    CONSTRAINT uq_maquina_canal
        UNIQUE (id_maquina, canal)
);


-- Índices para búsquedas rápidas.

CREATE INDEX IF NOT EXISTS idx_maquina_producto_maquina
ON public.maquina_producto(id_maquina);

CREATE INDEX IF NOT EXISTS idx_maquina_producto_producto
ON public.maquina_producto(id_producto);


COMMIT;

SELECT table_name, ordinal_position AS n, column_name, data_type, is_nullable, column_default
FROM information_schema.columns
WHERE table_schema = 'public'
  AND table_name IN ('categoria','impuesto','proveedor','producto',
                     'producto_proveedor','precio_tienda','margen_ganancia','bitacora_auditoria')
ORDER BY table_name, ordinal_position;

SELECT c.relname AS tabla, k.conname, k.contype, pg_get_constraintdef(k.oid) AS definicion
FROM pg_constraint k
JOIN pg_class c ON c.oid = k.conrelid
JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public'
  AND c.relname IN ('categoria','impuesto','proveedor','producto',
                    'producto_proveedor','precio_tienda','margen_ganancia','bitacora_auditoria')
  AND k.contype IN ('f','u','c')
ORDER BY c.relname, k.contype, k.conname;

