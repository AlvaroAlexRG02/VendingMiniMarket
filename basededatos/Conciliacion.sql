-- Ejecutar despues de crear el inventario base y basededatos/Ventas.sql.

ALTER TABLE public.venta_manual
    ADD COLUMN IF NOT EXISTS id_movimiento BIGINT UNIQUE
    REFERENCES public.movimiento_inventario(id_movimiento);

ALTER TABLE public.venta_manual_detalle
    ADD COLUMN IF NOT EXISTS costo_unitario NUMERIC(12,2)
    CHECK (costo_unitario IS NULL OR costo_unitario >= 0);

ALTER TABLE public.movimiento_inventario
    ADD COLUMN IF NOT EXISTS id_ubicacion_origen BIGINT
    REFERENCES public.ubicacion_inventario(id_ubicacion);

ALTER TABLE public.detalle_movimiento
    ADD COLUMN IF NOT EXISTS saldo_origen_anterior INTEGER,
    ADD COLUMN IF NOT EXISTS saldo_origen_resultante INTEGER;

CREATE TABLE IF NOT EXISTS public.conciliacion_venta (
    id_conciliacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    id_tienda BIGINT REFERENCES public.tienda(id_tienda),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_conciliacion_periodo CHECK (fecha_inicio <= fecha_fin)
);

CREATE TABLE IF NOT EXISTS public.conciliacion_venta_detalle (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_conciliacion BIGINT NOT NULL REFERENCES public.conciliacion_venta(id_conciliacion) ON DELETE CASCADE,
    id_tienda BIGINT NOT NULL REFERENCES public.tienda(id_tienda),
    id_ubicacion BIGINT NOT NULL REFERENCES public.ubicacion_inventario(id_ubicacion),
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    cantidad_vendida INTEGER NOT NULL DEFAULT 0,
    cantidad_movimiento INTEGER NOT NULL DEFAULT 0,
    diferencia_venta_movimiento INTEGER NOT NULL DEFAULT 0,
    existencia_actual INTEGER NOT NULL DEFAULT 0,
    saldo_ultimo_movimiento INTEGER,
    diferencia_existencia INTEGER,
    utilidad_estimada NUMERIC(12,2),
    lineas_sin_costo INTEGER NOT NULL DEFAULT 0,
    observacion VARCHAR(500),
    CONSTRAINT uq_conciliacion_venta_producto UNIQUE (id_conciliacion, id_ubicacion, id_producto)
);

CREATE TABLE IF NOT EXISTS public.ajuste_conciliacion_inventario (
    id_ajuste BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_detalle BIGINT NOT NULL REFERENCES public.conciliacion_venta_detalle(id_detalle),
    id_movimiento BIGINT NOT NULL UNIQUE REFERENCES public.movimiento_inventario(id_movimiento),
    id_usuario_autoriza BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    cantidad_antes INTEGER NOT NULL,
    cantidad_ajustada INTEGER NOT NULL CHECK (cantidad_ajustada <> 0),
    cantidad_despues INTEGER NOT NULL CHECK (cantidad_despues >= 0),
    observacion VARCHAR(500) NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_conciliacion_venta_periodo
    ON public.conciliacion_venta (fecha_inicio, fecha_fin, id_tienda);

CREATE INDEX IF NOT EXISTS idx_conciliacion_detalle_producto
    ON public.conciliacion_venta_detalle (id_ubicacion, id_producto);

CREATE INDEX IF NOT EXISTS idx_ajuste_conciliacion_detalle
    ON public.ajuste_conciliacion_inventario (id_detalle, fecha DESC);
