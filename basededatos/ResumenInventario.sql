-- HU-47: configuración y bitácora del resumen periódico de inventario.
-- Ejecutar después del esquema de inventario, Seguridad.sql y Alertas.sql.

BEGIN;

CREATE TABLE IF NOT EXISTS public.resumen_inventario_config (
    id_configuracion SMALLINT PRIMARY KEY DEFAULT 1
        CHECK (id_configuracion = 1),
    habilitado BOOLEAN NOT NULL DEFAULT FALSE,
    frecuencia VARCHAR(10) NOT NULL DEFAULT 'DIARIA'
        CHECK (frecuencia IN ('DIARIA', 'SEMANAL')),
    dia_semana SMALLINT NOT NULL DEFAULT 1
        CHECK (dia_semana BETWEEN 1 AND 7),
    hora TIME NOT NULL DEFAULT '07:00',
    correo_destino VARCHAR(254) NOT NULL,
    proxima_ejecucion TIMESTAMPTZ,
    id_usuario_configuracion BIGINT
        REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    fecha_configuracion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.resumen_inventario_ejecucion (
    id_ejecucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_configuracion BIGINT
        REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    correo_destino VARCHAR(254) NOT NULL,
    periodo_inicio DATE NOT NULL,
    periodo_fin DATE NOT NULL,
    estado_envio VARCHAR(15) NOT NULL DEFAULT 'PROCESANDO'
        CHECK (estado_envio IN ('PROCESANDO', 'ENVIADO', 'ERROR')),
    error TEXT,
    fecha_ejecucion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_finalizacion TIMESTAMPTZ,
    CONSTRAINT chk_resumen_inventario_periodo
        CHECK (periodo_inicio <= periodo_fin)
);

CREATE INDEX IF NOT EXISTS idx_resumen_inventario_ejecucion_fecha
    ON public.resumen_inventario_ejecucion (fecha_ejecucion DESC);

COMMIT;
