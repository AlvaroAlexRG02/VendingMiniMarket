-- No modifica registros existentes de ventas manuales ni existencias.
BEGIN;
CREATE TABLE IF NOT EXISTS public.importacion_nayax (
    id_importacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tienda BIGINT NOT NULL REFERENCES public.tienda(id_tienda),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    nombre_archivo VARCHAR(255) NOT NULL,
    sha256 CHAR(64) NOT NULL UNIQUE,
    periodo_inicio DATE NOT NULL,
    periodo_fin DATE NOT NULL,
    fecha_confirmacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    estado VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADA' CHECK (estado IN ('CONFIRMADA')),
    lineas INTEGER NOT NULL CHECK (lineas > 0),
    unidades INTEGER NOT NULL CHECK (unidades > 0),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    impuesto NUMERIC(14,2) NOT NULL CHECK (impuesto >= 0),
    total NUMERIC(14,2) NOT NULL CHECK (total >= 0),
    CONSTRAINT chk_importacion_nayax_periodo CHECK (periodo_inicio <= periodo_fin)
);
CREATE INDEX IF NOT EXISTS idx_importacion_nayax_periodo
    ON public.importacion_nayax (id_tienda, periodo_inicio, periodo_fin);

CREATE TABLE IF NOT EXISTS public.importacion_nayax_detalle (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_importacion BIGINT NOT NULL REFERENCES public.importacion_nayax(id_importacion),
    fila_excel INTEGER NOT NULL,
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    codigo_retail VARCHAR(100) NOT NULL,
    nombre_archivo_producto VARCHAR(350) NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    tasa_iva NUMERIC(7,4) NOT NULL CHECK (tasa_iva >= 0),
    subtotal NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
    impuesto NUMERIC(14,2) NOT NULL CHECK (impuesto >= 0),
    total NUMERIC(14,2) NOT NULL CHECK (total >= 0),
    CONSTRAINT uq_importacion_detalle_fila UNIQUE(id_importacion, fila_excel)
);
CREATE INDEX IF NOT EXISTS idx_importacion_detalle_producto
    ON public.importacion_nayax_detalle (id_producto, id_importacion);

CREATE TABLE IF NOT EXISTS public.importacion_nayax_movimiento (
    id_importacion BIGINT NOT NULL REFERENCES public.importacion_nayax(id_importacion),
    id_movimiento BIGINT NOT NULL UNIQUE REFERENCES public.movimiento_inventario(id_movimiento),
    PRIMARY KEY (id_importacion, id_movimiento)
);

-- El mapeo se guarda sin modificar el código retail del catálogo maestro.
CREATE TABLE IF NOT EXISTS public.nayax_codigo_mapeo (
    codigo_retail VARCHAR(100) PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Tabla ya contemplada por ReportesNayax.sql y config/reportes_lib.php.
CREATE TABLE IF NOT EXISTS public.venta_nayax (
    id_venta_nayax BIGSERIAL PRIMARY KEY,
    id_tienda BIGINT NOT NULL REFERENCES public.tienda(id_tienda),
    id_ubicacion BIGINT REFERENCES public.ubicacion_inventario(id_ubicacion),
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    referencia VARCHAR(100),
    fecha TIMESTAMPTZ NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12,2) NOT NULL DEFAULT 0,
    subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
    impuesto NUMERIC(12,2) NOT NULL DEFAULT 0,
    total NUMERIC(12,2) NOT NULL DEFAULT 0,
    costo_unitario NUMERIC(12,2),
    estado VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADA',
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_venta_nayax_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'ANULADA'))
);
ALTER TABLE public.venta_nayax
    ADD COLUMN IF NOT EXISTS id_importacion BIGINT REFERENCES public.importacion_nayax(id_importacion);
ALTER TABLE public.venta_nayax
    ADD COLUMN IF NOT EXISTS id_importacion_detalle BIGINT UNIQUE REFERENCES public.importacion_nayax_detalle(id_detalle);
CREATE INDEX IF NOT EXISTS idx_venta_nayax_tienda_fecha ON public.venta_nayax (id_tienda, fecha);
CREATE INDEX IF NOT EXISTS idx_venta_nayax_importacion ON public.venta_nayax (id_importacion);
COMMIT;
