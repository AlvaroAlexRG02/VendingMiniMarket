-- HU-54, HU-55 y HU-56: recomendaciones de baja rotación por tienda.
-- Requiere Seguridad.sql, Catalogoproductos.sql, Ventas.sql y el esquema
-- existente de inventario (existencia y ubicacion_inventario).

BEGIN;

CREATE TABLE IF NOT EXISTS public.recomendacion_producto_config (
    id_configuracion SMALLINT PRIMARY KEY DEFAULT 1
        CHECK (id_configuracion = 1),
    umbral_unidades INTEGER NOT NULL DEFAULT 5
        CHECK (umbral_unidades BETWEEN 1 AND 100000),
    id_usuario_actualizacion BIGINT
        REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO public.recomendacion_producto_config (id_configuracion, umbral_unidades)
VALUES (1, 5)
ON CONFLICT (id_configuracion) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.recomendacion_producto (
    id_recomendacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tienda BIGINT NOT NULL
        REFERENCES public.tienda(id_tienda) ON DELETE RESTRICT,
    id_producto BIGINT NOT NULL
        REFERENCES public.producto(id_producto) ON DELETE RESTRICT,
    periodo_inicio DATE NOT NULL,
    periodo_fin DATE NOT NULL,
    unidades_vendidas INTEGER NOT NULL CHECK (unidades_vendidas >= 0),
    umbral_unidades INTEGER NOT NULL CHECK (umbral_unidades >= 1),
    ventas_por_dia JSONB NOT NULL DEFAULT '[]'::JSONB,
    stock_actual INTEGER NOT NULL DEFAULT 0,
    ubicaciones TEXT,
    ia_explicacion TEXT,
    ia_modelo VARCHAR(100),
    ia_fecha_generacion TIMESTAMPTZ,
    ia_id_usuario BIGINT
        REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'REVISADA', 'ACEPTADA', 'DESCARTADA')),
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_recomendacion_periodo
        CHECK (periodo_inicio <= periodo_fin)
);

ALTER TABLE public.recomendacion_producto
    ADD COLUMN IF NOT EXISTS ia_explicacion TEXT,
    ADD COLUMN IF NOT EXISTS ia_modelo VARCHAR(100),
    ADD COLUMN IF NOT EXISTS ia_fecha_generacion TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS ia_id_usuario BIGINT
        REFERENCES public.usuario(id_usuario) ON DELETE SET NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_recomendacion_producto_activa
    ON public.recomendacion_producto (id_tienda, id_producto)
    WHERE estado IN ('PENDIENTE', 'REVISADA');

CREATE INDEX IF NOT EXISTS idx_recomendacion_producto_estado_fecha
    ON public.recomendacion_producto (estado, fecha_generacion DESC);

CREATE TABLE IF NOT EXISTS public.recomendacion_producto_historial (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recomendacion BIGINT NOT NULL
        REFERENCES public.recomendacion_producto(id_recomendacion) ON DELETE CASCADE,
    id_usuario BIGINT
        REFERENCES public.usuario(id_usuario) ON DELETE SET NULL,
    estado_anterior VARCHAR(15)
        CHECK (estado_anterior IS NULL OR estado_anterior IN ('PENDIENTE', 'REVISADA', 'ACEPTADA', 'DESCARTADA')),
    estado_nuevo VARCHAR(15) NOT NULL
        CHECK (estado_nuevo IN ('PENDIENTE', 'REVISADA', 'ACEPTADA', 'DESCARTADA')),
    comentario VARCHAR(1000),
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_recomendacion_producto_historial
    ON public.recomendacion_producto_historial (id_recomendacion, fecha DESC, id_historial DESC);

COMMIT;
